import type { ProgrammeReconciliation, RequirementLine } from './workbook-reconcile.js';

export interface ReconciledProgramme {
  programme: string;
  reconciliation: ProgrammeReconciliation;
}

const fmt = (value: number | null | undefined) => (value === null || value === undefined ? '—' : String(value));
const squash = (value: string) => value.toLowerCase().replace(/[^a-z0-9]/g, '');

/**
 * For "Pre-Calculus 1 / Calculus 1", which option belongs to the alternate track, judged by
 * the printed track name ("Pre-Calc", "Calc1&2"). A suggestion only: the Registry confirms it.
 */
export function suggestAlternateOption(options: string[], alternateTrack: string | null): number | null {
  if (!alternateTrack) return null;
  const track = squash(alternateTrack);
  const matches = options.map((option, index) => ({ index, name: squash(option) }))
    .filter(({ name }) => name.length > 0 && (name.startsWith(track) || track.startsWith(name.slice(0, Math.max(4, Math.min(name.length, track.length))))));
  return matches.length === 1 ? matches[0].index : null;
}

const csvCell = (value: string | number) => {
  const text = String(value);
  return /[",\n]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text;
};

export const MAPPING_COLUMNS = ['programme', 'section', 'category', 'kind', 'workbook_name', 'credits', 'track', 'source_row', 'course_code', 'minimum_grade', 'notes'];

function mappingRows(programme: string, alternateTrack: string | null, line: RequirementLine, creditsPrinted: boolean): string[][] {
  const uncredited = creditsPrinted ? '' : ' No credits are printed for this category: enter 0 if it carries none (the course is then listed but not counted).';
  const row = (name: string, track: string, notes: string) =>
    [programme, line.section, line.category, line.kind, name, String(line.credits), track, String(line.sourceRow), '', '', (notes + uncredited).trim()];
  switch (line.kind) {
    case 'ALTERNATIVE': {
      const options = line.name.split(' / ').map(option => option.trim());
      const alternate = suggestAlternateOption(options, alternateTrack);
      return options.map((option, index) => row(option,
        alternate === null ? 'confirm' : index === alternate ? `alternate (${alternateTrack})` : 'standard',
        `One of: ${line.name}. Track suggested from the printed track name; confirm.`));
    }
    case 'ALTERNATE_TRACK_ONLY':
      return [row(line.name, `alternate (${alternateTrack ?? 'confirm'})`, 'Counts only on the alternate track.')];
    case 'ELECTIVE_SLOTS':
      return [row(line.name, 'both', [
        `${line.credits} elective slot(s). List every allowed course code in course_code, separated by semicolons (CS 351; CS 352).`,
        line.africanStudiesMinimum ? `At least ${line.africanStudiesMinimum} must be African Studies: mark those codes with a trailing * (AS 101*).` : '',
        line.freeElectiveSlots ? `Includes ${line.freeElectiveSlots} free elective (major or non-major).` : ''
      ].filter(Boolean).join(' '))];
    case 'CONDITIONAL_CAPSTONE':
      return [row(line.name, 'both', 'May also count as a major elective; confirm the rule.')];
    case 'COURSE':
      return [row(line.name, 'both', line.credits === 0.5 ? 'Half-credit course (* in the workbook).' : '')];
  }
}

/**
 * One row per requirement line for the Registry to complete with course codes and pass marks
 * (blank minimum_grade means the provisional D+). Nothing is filled in by guesswork.
 */
export function mappingTemplateCsv(programmes: ReconciledProgramme[]): string {
  const rows = programmes.flatMap(({ programme, reconciliation }) =>
    reconciliation.lines.flatMap(line => mappingRows(programme, reconciliation.alternateTrack, line,
      reconciliation.totals.some(total => total.scope === 'CATEGORY' && total.label === line.category))));
  return [MAPPING_COLUMNS, ...rows].map(row => row.map(csvCell).join(',')).join('\r\n') + '\r\n';
}

const DISCREPANCY_TEXT: Record<string, string> = {
  CATEGORY_TOTAL_MISMATCH: 'Listed courses do not add up to the printed category total',
  SECTION_TOTAL_MISMATCH: 'Listed courses do not add up to the printed section total',
  SECTION_PRINTED_SUM_MISMATCH: 'Printed category totals do not add up to the printed section total',
  OVERALL_TOTAL_MISMATCH: 'Listed courses do not add up to the printed overall total',
  OVERALL_PRINTED_SUM_MISMATCH: 'Printed section totals do not add up to the printed overall total',
  CATEGORY_WITHOUT_TOTAL: 'Courses are listed, but no credit total is printed for them'
};

/** A Markdown report of every printed total checked against its components, for both tracks. */
export function reconciliationReport(programmes: ReconciledProgramme[], sourceSha256: string): string {
  const out: string[] = [
    '# Degree audit workbook reconciliation',
    '',
    `Source: \`Degree_Audit_2028.xlsx\`, SHA-256 \`${sourceSha256}\`. Generated by \`web-app/backend/scripts/ingest-degree-audit.ts\`.`,
    '',
    'How lines count: a course marked * is 0.5 credits, every other course 1. "A / B" is one course. A "(… track only)" or "(only if …)" course counts only on the alternate track. "n … Electives" is n credits of elective slots.',
    '',
    '## Summary',
    '',
    '| Programme | Alternate track | Overall printed (standard / alternate) | Overall computed | Discrepancies |',
    '|---|---|---|---|---|'
  ];
  for (const { programme, reconciliation: r } of programmes) {
    const overall = r.totals.find(total => total.scope === 'OVERALL');
    out.push(`| ${programme} | ${r.alternateTrack ?? '—'} | ${fmt(overall?.credits)} / ${fmt(overall?.alternateCredits)} | ${r.computed.standard.overall} / ${fmt(r.computed.alternate?.overall)} | ${r.discrepancies.length || 'none'} |`);
  }
  for (const { programme, reconciliation: r } of programmes) {
    out.push('', `## ${programme}`, '');
    out.push('| Category | Printed | Computed | Printed (alternate) | Computed (alternate) |', '|---|---|---|---|---|');
    for (const [label, credits] of Object.entries(r.computed.standard.categories)) {
      const total = r.totals.find(candidate => candidate.scope === 'CATEGORY' && candidate.label === label);
      const alternate = r.computed.alternate?.categories[label];
      out.push(`| ${label} | ${fmt(total?.credits)} | ${credits} | ${fmt(total?.alternateCredits)} | ${alternate === undefined || alternate === credits ? '' : alternate} |`);
    }
    if (r.discrepancies.length === 0) {
      out.push('', 'Every printed total matches its components.');
      continue;
    }
    out.push('', '| Finding | Where | Track | Computed | Printed | Row |', '|---|---|---|---|---|---|');
    for (const d of r.discrepancies) out.push(`| ${DISCREPANCY_TEXT[d.code]} | ${d.label} | ${d.track} | ${d.computed} | ${fmt(d.printed)} | ${d.sourceRow} |`);
  }
  const lineCount = programmes.reduce((sum, { reconciliation }) => sum + reconciliation.lines.length, 0);
  out.push('', `${lineCount} requirement lines in total.`, '');
  return out.join('\n');
}

